export type StringKey = keyof (typeof STRINGS)["ar"];
type StringFn = (n: number) => string;

export type TFunction = (key: StringKey, ...args: never[]) => string;

/** Current language + dir (rtl for ar). Swapped by the app shell. */
export function makeT(lang: Lang): TFunction {
  const table = STRINGS[lang] as Record<StringKey, string | StringFn>;
  return ((key: StringKey) => {
    const v = table[key];
    if (typeof v === "function") return v(0);
    return v;
  }) as TFunction;
}

export function isRtl(lang: Lang): boolean {
  return lang === "ar";
}

/** Arabic locale-aware collator for sorted name lists. */
export function arabicCollator(): Intl.Collator {
  try {
    return new Intl.Collator("ar", { sensitivity: "base" });
  } catch {
    return new Intl.Collator("en");
  }
}
